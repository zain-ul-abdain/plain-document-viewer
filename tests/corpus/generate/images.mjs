  write("images/complex.avif", Buffer.from(await encodeAvif(complex, { quality: 70, speed: 6 }))); rec("complex.avif", "complex", opens("AVIF", 0, 0), jsquash("avif"), { notes: "With transparency; the page reports 1200 × 800." });

