// RGBA pixels from a function of (x, y).
function pixels(width, height, pixel) {
  const data = new Uint8ClampedArray(width * height * 4);
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) data.set(pixel(x, y), (y * width + x) * 4);
  return { data, width, height, colorSpace: "srgb" };
}

function pngRgba({ data, width, height }) {
  const raw = Buffer.alloc((width * 4 + 1) * height);
  for (let y = 0; y < height; y++) Buffer.from(data.buffer, y * width * 4, width * 4).copy(raw, y * (width * 4 + 1) + 1);
  const chunk = (type, body) => {
    const length = Buffer.alloc(4); length.writeUInt32BE(body.length);
    const typed = Buffer.concat([Buffer.from(type, "ascii"), body]);
    const crc = Buffer.alloc(4); crc.writeUInt32BE(zlib.crc32(typed) >>> 0);
    return Buffer.concat([length, typed, crc]);
  };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(width, 0); ihdr.writeUInt32BE(height, 4); ihdr[8] = 8; ihdr[9] = 6;
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr), chunk("IDAT", zlib.deflateSync(raw, { level: 9 })), chunk("IEND", Buffer.alloc(0))]);
}

// 24-bit bottom-up BMP (alpha dropped).
function bmp({ data, width, height }) {
  const stride = Math.ceil(width * 3 / 4) * 4, size = 54 + stride * height, out = Buffer.alloc(size);
  out.write("BM", 0); out.writeUInt32LE(size, 2); out.writeUInt32LE(54, 10); out.writeUInt32LE(40, 14);
  out.writeInt32LE(width, 18); out.writeInt32LE(height, 22); out.writeUInt16LE(1, 26); out.writeUInt16LE(24, 28); out.writeUInt32LE(stride * height, 34);
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
    const s = ((height - 1 - y) * width + x) * 4, d = 54 + y * stride + x * 3;
    out[d] = data[s + 2]; out[d + 1] = data[s + 1]; out[d + 2] = data[s];
  }
  return out;
}

// An icon holding one PNG image (Windows Vista and later).
function ico(png, size) {
  const head = Buffer.alloc(22);
  head.writeUInt16LE(1, 2); head.writeUInt16LE(1, 4);
  head[6] = size >= 256 ? 0 : size; head[7] = size >= 256 ? 0 : size;
  head.writeUInt16LE(1, 10); head.writeUInt16LE(32, 12); head.writeUInt32LE(png.length, 14); head.writeUInt32LE(22, 18);
  return Buffer.concat([head, png]);
}

function viaGdi(png, format, extra = []) {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), "pv-gdi-"));
  try {
    const input = path.join(folder, "in.png"), output = path.join(folder, "out");
    fs.writeFileSync(input, png);
    execFileSync("powershell.exe", ["-NoProfile", "-ExecutionPolicy", "Bypass", "-File", path.join(here, "gdiplus.ps1"), input, output, format, ...extra.map(String)]);
    return fs.readFileSync(output);
  } finally { fs.rmSync(folder, { recursive: true, force: true }); }
}

const gradient = (w, h) => pixels(w, h, (x, y) => [Math.round(255 * x / w), Math.round(255 * y / h), 160, 255]);
// Transparent corners, coloured rings and a diagonal band, so decoding errors and wrong alpha are visible.
const complexArt = (w, h) => pixels(w, h, (x, y) => {
  const dx = x - w / 2, dy = y - h / 2, r = Math.hypot(dx, dy), ring = Math.floor(r / 24) % 3;
  const alpha = r > Math.min(w, h) * 0.48 ? 0 : 255;
  const band = Math.abs(x - y * w / h) < 18;
  return band ? [20, 20, 20, alpha] : [[217, 83, 79], [92, 184, 92], [66, 139, 202]][ring].concat(alpha);
});
const noise = (w, h) => pixels(w, h, (x, y) => { const v = (x * 7919 + y * 104729) % 251; return [v, (v * 3) % 256, (x ^ y) & 255, 255]; });

const rec = (file, category, expect, producer, extra = {}) =>
  record({ id: `image-${file.replace(/[/.]/g, "-")}`, file: `images/${file}`, format: path.extname(file).slice(1), category, producer, licence, expect, rules: SAFE_RULES, ...extra });
const opens = (format, width, height) => ({ result: "open", format, width, height });

